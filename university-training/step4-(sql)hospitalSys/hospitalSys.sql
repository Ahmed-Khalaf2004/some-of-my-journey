DROP TABLE VISITS CASCADE CONSTRAINTS;
DROP TABLE PATIENTS CASCADE CONSTRAINTS;
DROP TABLE DOCTORS CASCADE CONSTRAINTS;
CREATE TABLE DOCTORS (
    DOCTOR_ID NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1) PRIMARY KEY,
    DOCTOR_NAME VARCHAR2(100) NOT NULL,
    SPECIALTY VARCHAR2(100) NOT NULL,
    PHONE VARCHAR2(20),
    HIRE_DATE DATE DEFAULT SYSDATE
);

CREATE TABLE PATIENTS (
    PATIENT_ID NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 101 INCREMENT BY 1) PRIMARY KEY,
    FIRST_NAME VARCHAR2(50) NOT NULL,
    LAST_NAME VARCHAR2(50) NOT NULL,
    GENDER VARCHAR2(10),
    BIRTH_DATE DATE,
    PHONE VARCHAR2(20),
    CITY VARCHAR2(100)
);

CREATE TABLE VISITS (
    VISIT_ID NUMBER GENERATED ALWAYS AS IDENTITY (START WITH 1001 INCREMENT BY 1) PRIMARY KEY,
    PATIENT_ID NUMBER NOT NULL,
    DOCTOR_ID NUMBER NOT NULL,
    VISIT_DATE DATE DEFAULT SYSDATE,
    DIAGNOSIS VARCHAR2(200),
    STATUS VARCHAR2(20),
    CONSTRAINT FK_VISITS_PATIENTS FOREIGN KEY (PATIENT_ID) REFERENCES PATIENTS(PATIENT_ID),
    CONSTRAINT FK_VISITS_DOCTORS FOREIGN KEY (DOCTOR_ID) REFERENCES DOCTORS(DOCTOR_ID)
);



