CREATE OR REPLACE FUNCTION GET_PATIENT_VISITS_COUNT(
    p_patient_id IN NUMBER
) RETURN NUMBER AS
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM VISITS
    WHERE PATIENT_ID = p_patient_id;
    
    RETURN v_count;
